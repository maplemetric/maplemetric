package com.maplemetric.common.nexon;

/**
 * 요청이 어느 호출 예산을 쓰는지 나타낸다.
 *
 * Nexon은 하루 한도도 애플리케이션 단위로 센다. Key를 모두 한 덩어리로 쓰면 한
 * 종류의 부하가 하루 한도를 다 먹었을 때 다른 종류까지 함께 멈춘다. 등급을 나눠
 * Key를 갈라 두면 한쪽이 바닥나도 다른 쪽 예산이 남는다.
 *
 * 등급은 부르는 쪽의 업무 이름이 아니라 예산의 성격이다. 여기서 {@code BACKFILL}
 * 같은 이름을 쓰면 이 관문이 어느 모듈이 부르는지 알게 된다.
 */
public enum NexonRequestClass {

    /** 실패하면 안 되는 요청이다. 정기 수집과 사용자 요청이 여기 든다. */
    CRITICAL,

    /** 미뤄도 되는 대량 요청이다. 과거 결손 메우기가 여기 든다. */
    BULK
}
