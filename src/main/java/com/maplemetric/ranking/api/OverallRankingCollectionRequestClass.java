package com.maplemetric.ranking.api;

/**
 * 수집이 어느 호출 예산을 쓰는지 부르는 쪽이 밝힌다.
 *
 * 외부 API는 하루 호출 수에 한도가 있다. 과거 결손을 메우는 수집은 기준일마다
 * 호출을 쓰기 때문에, 정기 수집과 같은 예산을 쓰면 하루 한도를 먼저 다 써서 그날
 * 정기 수집을 실패시킨다.
 *
 * 등급을 밝히면 수집 계층이 예산을 갈라 쓴다. 어느 모듈이 불렀는지로 짐작하지 않는
 * 이유는, 짐작이 틀렸을 때 조용히 예산을 침범하고 시험할 방법도 없기 때문이다.
 */
public enum OverallRankingCollectionRequestClass {

    /** 실패하면 안 되는 수집이다. 정기 수집과 사람이 누른 수집이 여기 든다. */
    CRITICAL,

    /** 미뤄도 되는 대량 수집이다. 과거 결손 메우기가 여기 든다. */
    BULK
}
